"""Inspect GraphRAG parquet output and write docs/schema_notes.md."""
from __future__ import annotations

import logging
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from backend.config import OUTPUT_DIR, PROJECT_ROOT  # noqa: E402

logger = logging.getLogger("inspect_output")
KEY_TABLES = ["entities", "relationships", "communities", "community_reports", "text_units", "documents"]


def sample(df: pd.DataFrame) -> dict:
    """First row with long values truncated."""
    if df.empty:
        return {}
    return {k: (str(v)[:80] + "...") if len(str(v)) > 80 else v for k, v in df.iloc[0].to_dict().items()}


def main() -> int:
    """Print a summary of every parquet file and write schema notes."""
    files = sorted(OUTPUT_DIR.glob("*.parquet"))
    if not files:
        logger.error("No parquet files in %s. Run the indexer first.", OUTPUT_DIR)
        return 1
    tables = {f.stem: pd.read_parquet(f) for f in files}
    for name, df in tables.items():
        logger.info("%s: %d rows\n  columns: %s\n  sample: %s", name, len(df), list(df.columns), sample(df))

    rel = tables.get("relationships", pd.DataFrame())
    tu = tables.get("text_units", pd.DataFrame())
    rel_link = "text_unit_ids" in rel.columns and rel["text_unit_ids"].map(lambda v: len(v) > 0).all()
    tu_link = "document_id" in tu.columns and tu["document_id"].notna().all()
    logger.info("relationships carry text_unit_ids: %s", rel_link)
    logger.info("text_units link to documents: %s", tu_link)

    lines = ["# GraphRAG output schema notes", "",
             f"Generated by `scripts/inspect_output.py` from `{OUTPUT_DIR.relative_to(PROJECT_ROOT)}`.", "",
             "## Link checks", "",
             f"- relationships have non-empty `text_unit_ids`: **{rel_link}**",
             f"- text_units link to documents via `document_id`: **{tu_link}**", "",
             "## Tables", ""]
    for name in KEY_TABLES + [n for n in tables if n not in KEY_TABLES]:
        if name not in tables:
            lines += [f"### {name}", "", "_missing_", ""]
            continue
        df = tables[name]
        lines += [f"### {name} ({len(df)} rows)", "", "| column | dtype |", "|---|---|"]
        lines += [f"| `{c}` | {df[c].dtype} |" for c in df.columns]
        lines.append("")
    lines += ["## Query context id conventions (graphrag 3.3)", "",
              "- global `reports[].id` = community number (`community_reports.community`)",
              "- local `entities[].entity` = `entities.title`; `entities[].id` = `entities.human_readable_id`",
              "- local `relationships[].id` = `relationships.human_readable_id`",
              "- `sources[].id` = row position of the text unit; ThemeGraph maps sources to documents by text match",
              "- entities have no community column; membership comes from `communities.entity_ids` (per level)", ""]
    out = PROJECT_ROOT / "docs" / "schema_notes.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote %s", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
